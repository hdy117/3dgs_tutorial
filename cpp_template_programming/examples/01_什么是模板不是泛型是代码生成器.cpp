/* ================================================================
 *  Chapter 01 — 什么是模板？不是泛型，是编译期代码生成器
 * ================================================================
 *
 * 🧠 第一性原理推导：
 * ──────────────────
 *  前提1: C++是静态类型语言 → 编译时必须知道所有类型
 *  前提2: 零开销原则       → 抽象不应带来运行时成本
 *  前提3: DRY原则          → 不想为 int/float/double 各写一份swap
 *
 *  推导: 要同时满足以上三点，唯一的方案是——在编译期"复制代码+替换类型"
 *  结论: 模板就是"带占位符的代码 + 编译期实例化"
 *
 * 💡 Mental Model:
 *   template<typename T> void swap(T& a, T& b) { ... }
 *   
 *   当你调用 swap<int>(x, y)，编译器做的事情：
 *   1. 把函数体里的每个 T 替换成 int
 *   2. 生成一份完整的 swap_int 函数
 *   3. 这份函数的性能和手写的一模一样（零开销！）
 *   
 *   这不是"泛型"——Python的Generic在运行时工作。
 *   这是"代码生成器"——C++的模板在编译期工作。
 *
 * ================================================================ */

#include <iostream>
#include <string>
using namespace std;

// ──────────────────────────────────────────────────────────────────
// 1. 最基础的函数模板
//    看：T是一个占位符，编译器会在调用时自动推断类型
// ──────────────────────────────────────────────────────────────────
template<typename T>
void print_value(T value) {
    cout << "打印: [" << value << "]" << endl;
}

// ──────────────────────────────────────────────────────────────────
// 2. 模板 vs 非模板的对比 —— 这就是"零开销"的意义
//    
//    如果没有模板，你要写：
//      void print_int(int v) { cout << v; }
//      void print_double(double v) { cout << v; }
//      void print_string(string v) { cout << v; }
//    
//    有了模板，只需写一次，编译器自动生成上面所有版本。
// ──────────────────────────────────────────────────────────────────

int main() {
    // ======================== 实验1: 自动类型推断 ========================
    // 调用 print_value(42) 时，编译器看到字面量42是int类型，
    // 于是把 T 替换为 int，生成 print_value<int>。
    
    cout << "=== 自动类型推断 ===" << endl;
    print_value(42);         // T = int, 编译器生成了 print_value<int>
    print_value(3.14);       // T = double, 编译器生成了 print_value<double>
    print_value(string("hello"));  // T = string
    
    cout << "\n";
    
    // ======================== 实验2: 手动指定类型 ========================
    // 有时候自动推断会出错（比如模板推导失败），这时可以强制指定：
    //   print_value<int>(42);     ← 明确告诉编译器 T=int
    
    cout << "=== 手动指定类型 ===" << endl;
    print_value<double>(99);   // 虽然传的是int，但T被强制为double → 输出99.00
    
    cout << "\n";
    
    // ======================== 实验3: 理解"代码生成"的本质 ===============
    // 这是最关键的理解：模板不是运行时多态。
    // 编译器在编译期就生成了完全不同的函数实例。
    
    cout << "=== 核心洞察 ===" << endl;
    cout << "每次调用不同T，都是生成一个新函数！\n";
    cout << "print_value<int> 和 print_value<double> 是两个毫无关系的独立函数。\n";
    cout << "它们共享同一段源代码，但生成的汇编代码完全不同。\n";
    
    // ======================== 实验4: 模板不是万能胶水 =====================
    // 如果你传一个不支持 << 的类型，编译会报错：
    //   struct Foo {}; 
    //   print_value(Foo{});     // ❌ ERROR! Foo没有operator<<
    //
    // 这说明：模板不保证"类型兼容"，只保证"语法替换"。
    // T=int时，函数体内所有代码必须对int合法。
    
    cout << "\n";
    cout << "🎯 本章要点:\n";
    cout << "1. template<typename T> = 写一个占位符版本的代码\n";
    cout << "2. 编译器在调用点自动推断T并生成具体版本\n";
    cout << "3. 零开销：生成的代码和手写的一样快\n";
    cout << "4. 模板 ≠ 运行时多态，它是编译期代码替换\n";
    
    return 0;
}
